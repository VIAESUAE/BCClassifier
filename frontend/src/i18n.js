export function useI18n() {
  const t = computed(() => messages[locale.value] || messages.zh)
  const examples = computed(() =>
    locale.value === 'zh' ? messages.zh.examplesZh : messages.en.examplesEn,
  )
  return { locale, setLocale, t, examples }
}
